/**
 * Builds the Ideas map once, ahead of time:
 *   npx tsx scripts/map/build.ts
 * Reads country outlines from world-atlas (Natural Earth, public domain),
 * projects western North America onto a flat picture, and writes the shapes
 * and the position of each research area to src/lib/ideas/map-data.ts.
 * The app then draws plain SVG: no map library, no map service, no key.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { geoConicConformal, geoPath } from "d3-geo";
import { feature } from "topojson-client";
import type { Topology, GeometryCollection } from "topojson-specification";
import { REGIONS } from "../../src/lib/ideas/regions";

const WIDTH = 1000;
const HEIGHT = 600;

// Where each research area's marker sits [longitude, latitude].
const PLACES: Record<string, [number, number]> = {
  "british-columbia": [-124.5, 53.8],
  alberta: [-114.8, 54.6],
  saskatchewan: [-105.9, 54.3],
  manitoba: [-97.6, 54.6],
  "western-canada": [-111.5, 60.4],
  "pacific-northwest": [-120.8, 46.2],
  "permian-basin": [-102.6, 31.9],
  "us-gulf-coast": [-93.8, 30.2],
};

const topo = JSON.parse(readFileSync("node_modules/world-atlas/countries-110m.json", "utf8")) as Topology<{ countries: GeometryCollection<{ name: string }> }>;
const countries = feature(topo, topo.objects.countries);
const keep: Record<string, "canada" | "usa" | "other"> = { "124": "canada", "840": "usa", "484": "other" };
const shapes = countries.features.filter((f) => keep[String(f.id)]);

// Frame: western Canada down to the Gulf of Mexico, with the east of the
// continent left in view so the details card can sit over it.
const frame = {
  type: "Feature" as const,
  properties: {},
  geometry: { type: "MultiPoint" as const, coordinates: [[-134, 61], [-66, 61], [-68, 26], [-128, 27], [-100, 25]] },
};
const projection = geoConicConformal().parallels([30, 60]).rotate([100, 0]).fitExtent([[30, 30], [WIDTH - 30, HEIGHT - 30]], frame);
projection.clipExtent([[0, 0], [WIDTH, HEIGHT]]);
const path = geoPath(projection);
const round = (d: string) => d.replace(/-?\d+\.\d+/g, (n) => (Math.round(Number(n) * 10) / 10).toString());

const land = shapes.map((f) => ({ country: keep[String(f.id)], d: round(path(f) ?? "") })).filter((s) => s.d);
const places = REGIONS.map((r) => {
  const [x, y] = projection(PLACES[r.slug])!;
  return { slug: r.slug, x: Math.round(x), y: Math.round(y) };
});

const out = `// Generated by scripts/map/build.ts from world-atlas (Natural Earth, public domain). Do not edit by hand.
export const MAP_SIZE = { width: ${WIDTH}, height: ${HEIGHT} } as const;
export const MAP_LAND: { country: "canada" | "usa" | "other"; d: string }[] = ${JSON.stringify(land)};
export const MAP_PLACES: { slug: string; x: number; y: number }[] = ${JSON.stringify(places)};
`;
writeFileSync("src/lib/ideas/map-data.ts", out);
console.log({ shapes: land.length, kb: Math.round(out.length / 1024), places });
